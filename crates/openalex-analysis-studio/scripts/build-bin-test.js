#!/usr/bin/env node
// Hand-test build: GUI is compiled with bin-test-frontend feature and loads
// ./cistella-frontend/index.html next to the executable instead of embedded assets.
import { execSync } from 'node:child_process';
import { cpSync, copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const crateDir = resolve(__dirname, '..');
const workspaceRoot = resolve(crateDir, '..', '..');
const tauriConf = JSON.parse(readFileSync(join(crateDir, 'src-tauri', 'tauri.conf.json'), 'utf8'));
const productName = tauriConf.productName || 'cistella';
const version = tauriConf.version || '0.1.0';
const releaseDir = join(workspaceRoot, 'target', 'release');
const guiExeName = `${productName}.exe`;
const headlessExeName = `${productName}-headless.exe`;
const guiExePath = join(releaseDir, guiExeName);
const headlessExePath = join(releaseDir, headlessExeName);
const binTestDir = join(workspaceRoot, 'bin_test');
const frontendDir = join(binTestDir, 'cistella-frontend');
const portableDir = join(binTestDir, 'cistella-portable');

function run(command) {
  execSync(command, { cwd: crateDir, stdio: 'inherit', shell: true });
}

run('pnpm build');
run('cargo build --release --bin cistella --features bin-test-frontend');
run('cargo build --release --bin cistella-headless');

for (const artifact of [guiExePath, headlessExePath, join(crateDir, 'dist', 'index.html')]) {
  if (!existsSync(artifact)) {
    throw new Error(`Expected bin_test artifact was not produced: ${artifact}`);
  }
}

rmSync(binTestDir, { recursive: true, force: true });
mkdirSync(portableDir, { recursive: true });
cpSync(join(crateDir, 'dist'), frontendDir, { recursive: true });
copyFileSync(guiExePath, join(binTestDir, guiExeName));
copyFileSync(headlessExePath, join(binTestDir, headlessExeName));
writeFileSync(
  join(binTestDir, 'README.txt'),
  [
    `${productName} bin_test hand-test layout`,
    `Version: ${version}`,
    '',
    'This directory is generated by scripts/build-bin-test.js.',
    'The GUI executable is compiled with --features bin-test-frontend and',
    'loads ./cistella-frontend/index.html through the cistella-bin-test protocol.',
    '',
    `- ${guiExeName}: bin_test GUI launcher, NOT the embedded release GUI`,
    `- ${headlessExeName}: headless work-order utility`,
    `- cistella-frontend/: external frontend assets for hot hand-test updates`,
    `- cistella-portable/: portable state marker`,
    '',
    'For frontend-only refreshes, run pnpm build and copy dist/ over cistella-frontend/.',
    'For final embedded release, use scripts/build-release.js instead.',
    '',
  ].join('\r\n'),
  'utf8'
);

console.log(`bin_test generated: ${binTestDir}`);
